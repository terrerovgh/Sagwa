"""Prepare downloaded Google Noto animations for the CoreS3, offline and deterministic.
Only resampling, palette reduction and RGB565 conversion; original art is retained.
"""
import hashlib,json,math,struct
from pathlib import Path
from PIL import Image
root=Path(__file__).resolve().parents[1]
source=root/'assets/noto';dest=root/'firmware/components/agentshell_ui'
entries=[('smile','1f60a',96),('robot','1f916',96),('cat','1f431',96),('thinking','1f914',96),('sleeping','1f634',96),('concerned','1f61f',96),('listening','1f442',32),('approval','1f512',32),('speaking','1f4ac',32),('warning','26a0',32),('executing','2699',32),('delegating','1f91d',32),('thinking','1f914',32),('sleeping','1f634',32)]
blob=bytearray();metadata=[]
for name,code,size in entries:
 path=source/(name+'.gif');im=Image.open(path);frames=[];times=[];duration=0
 for index in range(im.n_frames):
  im.seek(index);times.append(duration);duration+=im.info.get('duration',100)
  base=Image.new('RGBA',im.size,(8,19,31,255));base.alpha_composite(im.convert('RGBA'))
  frames.append(base.convert('RGB').resize((size,size),Image.Resampling.LANCZOS))
 count=max(2,min(30,round(duration/100)));chosen=[]
 for i in range(count):
  at=duration*i/count;idx=max(j for j,t in enumerate(times) if t<=at);chosen.append(frames[idx])
 # One palette per animation prevents frame-to-frame colour flicker.
 atlas=Image.new('RGB',(size,size*count))
 for i,frame in enumerate(chosen):atlas.paste(frame,(0,size*i))
 indexed=atlas.quantize(colors=127,method=Image.Quantize.MEDIANCUT,dither=Image.Dither.NONE)
 palette=indexed.getpalette();palette_offset=len(blob)
 for j in range(128):
  r,g,b=(8,19,31) if j==0 else palette[(j-1)*3:(j-1)*3+3];value=((r>>3)<<11)|((g>>2)<<5)|(b>>3);blob+=struct.pack('<H',value)
 rgb=atlas.tobytes();offset=len(blob)
 blob+=bytes(0 if rgb[n*3:n*3+3]==b'\x08\x13\x1f' else index+1 for n,index in enumerate(indexed.tobytes()))
 metadata.append({'name':name+('_badge' if size==32 else ''),'source_name':name,'codepoint':code,'source_url':f'https://fonts.gstatic.com/s/e/notoemoji/latest/{code}/512.gif','source_sha256':hashlib.sha256(path.read_bytes()).hexdigest(),'width':size,'height':size,'frames':count,'duration_ms':duration,'palette_offset':palette_offset,'data_offset':offset})
(dest/'noto.bin').write_bytes(blob)
(source/'manifest.json').write_text(json.dumps({'creator':'Google','collection':'Animated Noto Emoji','source':'https://googlefonts.github.io/noto-emoji-files/','license':'CC-BY-4.0','license_url':'https://creativecommons.org/licenses/by/4.0/','changes':'Resized, sampled at approximately 10 fps, composited on navy, reduced to 128 colours and converted to RGB565.','packed_sha256':hashlib.sha256(blob).hexdigest(),'animations':metadata},indent=2)+'\n')
header='''// Generated by scripts/export-noto.py. Art: Google Noto Emoji, CC BY 4.0.
#pragma once
#include <cstdint>
namespace shell {
struct Animation { const char *name; uint16_t width,height,frames,duration_ms; uint32_t palette_offset,data_offset; };
inline constexpr Animation animations[] = {
'''
for a in metadata:header+='  {"%s",%d,%d,%d,%d,%d,%d},\n'%(a['name'],a['width'],a['height'],a['frames'],a['duration_ms'],a['palette_offset'],a['data_offset'])
header+='};\nstruct Graphic { unsigned avatar,frame; int badge; unsigned badge_frame; };\n}\n'
(dest/'noto.hpp').write_text(header)
(source/'CREDITS.md').write_text('''# Animated Noto Emoji

Artwork and animations by **Google**, licensed under **Creative Commons Attribution 4.0 International (CC BY 4.0)**.

- Original collection and documentation: https://googlefonts.github.io/noto-emoji-files/
- License and disclaimer: https://creativecommons.org/licenses/by/4.0/
- Original CDN URLs and SHA-256 hashes: `manifest.json`.

AgentShell adaptations: resized, sampled to approximately 10 FPS, composited on a navy background, palette reduced to 128 colours and converted to RGB565. The original downloaded GIF files are included here. No endorsement by Google is implied. Attribution also appears on the terminal screen.

Regenerate with `python agentshell/scripts/export-noto.py` (Pillow required). Downloads are not performed during firmware compilation; the packed bytes and metadata are checked into the project.
''')
print(json.dumps({'packed_bytes':len(blob),'animations':len(entries),'sha256':hashlib.sha256(blob).hexdigest()}))
